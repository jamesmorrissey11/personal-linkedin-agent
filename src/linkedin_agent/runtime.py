"""Shared runtime helpers: where runtime state lives, errors, report counts, console logging, and notifications.

Runtime state (the LinkedIn login session and lock, the LangGraph server's review data, and logs) lives in one
per-user folder outside the repo, so every checkout and worktree sees the same Agent Inbox and nothing
generated by running the agent lands in the repo. Override the location with LINKEDIN_AGENT_HOME.
"""

import asyncio
import logging
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

logger = logging.getLogger("unattended")

STATE_HOME_ENV = "LINKEDIN_AGENT_HOME"
APP_NAME = "linkedin-agent"


def state_dir() -> Path:
    """The per-user runtime folder: $LINKEDIN_AGENT_HOME, else the platform's per-user application folder."""
    if override := os.environ.get(STATE_HOME_ENV):
        return Path(override).expanduser()
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / APP_NAME
    return Path(os.environ.get("XDG_STATE_HOME") or Path.home() / ".local" / "state") / APP_NAME


def browser_dir() -> Path:
    """The cached LinkedIn login (`state.json`) and the cross-process LinkedIn lock."""
    return state_dir() / "browser"


def langgraph_dir() -> Path:
    """Working directory of the LangGraph dev server, which keeps Agent Inbox review data in `.langgraph_api/` here."""
    return state_dir() / "langgraph"


def logs_dir() -> Path:
    return state_dir() / "logs"


def configure_console_logging() -> None:
    """Rich console logging for CLI runs; called once at startup, never at import."""
    from rich.logging import RichHandler

    logging.basicConfig(level=logging.WARNING, format="%(message)s", datefmt="[%X]", handlers=[RichHandler(show_level=True)])


# Stop scanning once this many consecutive items are already known (queued, applied, superseded, or self-replied).
KNOWN_STREAK_STOP = 5


class LoginRequiredError(RuntimeError):
    """The cached LinkedIn session expired and no human is available to log in."""


class SetupError(RuntimeError):
    """A setup problem the user can fix (server not running, backend unreachable, missing settings).

    The CLI prints `cause` and `fix` on one line instead of a traceback.
    """

    def __init__(self, cause: str, fix: str):
        super().__init__(f"{cause} {fix}")
        self.cause = cause
        self.fix = fix


AGENT_INBOX_URL = "http://localhost:3000"


def next_step(counts: "ReviewCounts", graph_label: str, command: str) -> str:
    """The one thing to do after a run, shown at the end of every manual run."""
    if counts.new:
        return f"Next: review {counts.new} new {graph_label} item(s) in Agent Inbox ({AGENT_INBOX_URL}). Accept, Edit, or Ignore acts on LinkedIn right away."
    if counts.cap_hit:
        return f"Next: more may be waiting past the safety cap; run `uv run linkedin-agent {command}` again with a higher cap."
    return f"Nothing new to review. Next: `uv run linkedin-agent {command}` again later, or let the 06:30 daily sync run."


def check_url(url: str, cause: str, fix: str, timeout: float = 3.0) -> None:
    """Raise SetupError when `url` doesn't answer; used to fail fast before opening LinkedIn."""
    import urllib.error
    import urllib.request

    try:
        with urllib.request.urlopen(url, timeout=timeout):
            return
    except urllib.error.HTTPError:
        return  # the server answered, which is all this check is for
    except (OSError, ValueError) as error:
        raise SetupError(cause, fix) from error


class HealthCheckError(RuntimeError):
    """A scrape looked broken (e.g. zero cards), so the result can't be trusted and nothing is closed."""


@dataclass
class ReviewCounts:
    """Split counts for one run so already-handled items are never double counted."""

    new: int = 0
    already_queued: int = 0
    applied: int = 0
    superseded: int = 0
    needs_judgment: int = 0
    cap_hit: bool = False

    @property
    def total(self) -> int:
        return self.new + self.already_queued + self.applied + self.superseded

    def __add__(self, other: "ReviewCounts") -> "ReviewCounts":
        return ReviewCounts(
            self.new + other.new,
            self.already_queued + other.already_queued,
            self.applied + other.applied,
            self.superseded + other.superseded,
            self.needs_judgment + other.needs_judgment,
            self.cap_hit or other.cap_hit,
        )

    def describe(self) -> str:
        text = f"{self.new} new, {self.already_queued} already queued, {self.applied} applied, {self.superseded} superseded ({self.total} total; {self.needs_judgment} need judgment)"
        return text + " - SAFETY CAP HIT, increase the limit" if self.cap_hit else text


def notify(title: str, message: str) -> None:
    """Post a macOS notification; on other platforms (or on failure) only log it."""
    logger.info("NOTIFY %s: %s", title, message)
    if sys.platform != "darwin":
        return
    script = ["on run argv", "display notification (item 1 of argv) with title (item 2 of argv)", "end run"]
    command = ["osascript"] + [part for line in script for part in ("-e", line)] + [message, title]
    try:
        subprocess.run(command, check=False, timeout=10, capture_output=True)
    except (OSError, subprocess.SubprocessError) as error:
        logger.warning("Could not post notification: %s", error)


async def notify_async(title: str, message: str) -> None:
    """Post a notification from async code without blocking the event loop.

    notify() shells out to osascript. Called directly from a graph node that would be a blocking
    subprocess call on the event loop, which `langgraph dev`'s blockbuster turns into an error that
    aborts the run. Notifications are also best-effort: a failure here must never fail an action that
    already took effect on LinkedIn.
    """
    try:
        await asyncio.to_thread(notify, title, message)
    except Exception as error:
        logger.warning("Could not post notification: %s", error)
